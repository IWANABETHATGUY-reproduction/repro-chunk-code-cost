// Generates a module graph that has the shape of the captured build:
// one entry, many dynamic-import routes, each route with its own leaf modules
// plus a few modules from a shared pool. Shared modules used by different
// route subsets become many small common chunks.
import fs from 'node:fs';
import path from 'node:path';

// PRESET=default: 40,001 modules, about 6,400 chunks, about 185 MB of output.
// PRESET=large: about 84,000 modules, about 15,000 chunks, about 500 MB of output (half the captured build).
// Any explicit env value overrides the preset.
const PRESETS = {
  default: { ROUTES: 4000, LEAVES_PER_ROUTE: 8, SHARED: 4000, SHARED_PER_ROUTE: 2, MODULE_BYTES: 5000 },
  large: { ROUTES: 8000, LEAVES_PER_ROUTE: 8, SHARED: 12000, SHARED_PER_ROUTE: 3, MODULE_BYTES: 6500 },
};
const PRESET = PRESETS[process.env.PRESET ?? 'default'];
if (!PRESET) { console.error(`unknown PRESET ${process.env.PRESET}; use ${Object.keys(PRESETS).join(' or ')}`); process.exit(1); }
const num = (k, d) => (process.env[k] !== undefined ? Number(process.env[k]) : (PRESET[k] ?? d));
const ROUTES = num('ROUTES', 4000);
const LEAVES = num('LEAVES_PER_ROUTE', 8);
const SHARED = num('SHARED', 4000);
const SHARED_PER_ROUTE = num('SHARED_PER_ROUTE', 2);
const BYTES = num('MODULE_BYTES', 5000);
const NON_ASCII = num('NON_ASCII', 0);
const NON_ASCII_SHARE = num('NON_ASCII_SHARE', 0.02); // share of words taken from the non-ASCII list when NON_ASCII=1
const SEED = num('SEED', 1);
const SRC = path.resolve(process.env.SRC_DIR ?? 'src');

let s = SEED >>> 0 || 1;
const rand = () => {
  s += 0x6d2b79f5;
  let t = Math.imul(s ^ (s >>> 15), 1 | s);
  t ^= t + Math.imul(t ^ (t >>> 7), 61 | t);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};
const WORDS = 'alpha bravo charlie delta echo foxtrot golf hotel india juliet kilo lima mike november oscar papa quebec romeo sierra tango uniform victor whiskey xray yankee zulu'.split(' ');
const NA = ['中文', '日本語', 'café', 'naïve', 'Ünïcödé'];
function filler(bytes) {
  const parts = [];
  let n = 0;
  while (n < bytes) {
    const w = NON_ASCII && rand() < NON_ASCII_SHARE ? NA[Math.floor(rand() * NA.length)] : WORDS[Math.floor(rand() * WORDS.length)];
    parts.push(w);
    n += w.length + 1;
  }
  return parts.join(' ');
}
function leafSource(ident) {
  return `// ${ident}\nconst data = ${JSON.stringify(filler(BYTES))};\nexport function ${ident}(x) {\n  return data.charCodeAt(x % data.length) + x;\n}\n`;
}

const marker = path.join(SRC, '.generated-by-gen-mjs');
if (fs.existsSync(SRC)) {
  if (!fs.existsSync(marker)) {
    console.error(`refusing to delete ${SRC}: it was not generated by this script`);
    process.exit(1);
  }
  fs.rmSync(SRC, { recursive: true, force: true });
}
for (const d of ['routes', 'leaves', 'shared']) fs.mkdirSync(path.join(SRC, d), { recursive: true });
fs.writeFileSync(marker, '');

let files = 0;
let bytes = 0;
const write = (rel, content) => {
  fs.writeFileSync(path.join(SRC, rel), content);
  files++;
  bytes += content.length;
};

for (let k = 0; k < SHARED; k++) write(`shared/s${k}.js`, leafSource(`s${k}`));

const routeImports = [];
for (let i = 0; i < ROUTES; i++) {
  const imports = [];
  const calls = [];
  for (let j = 0; j < LEAVES; j++) {
    const ident = `r${i}_l${j}`;
    write(`leaves/${ident}.js`, leafSource(ident));
    imports.push(`import { ${ident} } from '../leaves/${ident}.js';`);
    calls.push(`${ident}(x)`);
  }
  const picked = new Set();
  while (picked.size < Math.min(SHARED_PER_ROUTE, SHARED)) picked.add(Math.floor(rand() * SHARED));
  for (const k of picked) {
    imports.push(`import { s${k} } from '../shared/s${k}.js';`);
    calls.push(`s${k}(x)`);
  }
  write(`routes/r${i}.js`, `${imports.join('\n')}\nexport const name = 'r${i}';\nexport function load(x) {\n  return ${calls.join(' + ')};\n}\n`);
  routeImports.push(`  () => import('./routes/r${i}.js'),`);
}
write('main.js', `export const routes = [\n${routeImports.join('\n')}\n];\nexport async function loadAll() {\n  let n = 0;\n  for (const r of routes) n += (await r()).load(1);\n  return n;\n}\n`);

console.log(JSON.stringify({ preset: process.env.PRESET ?? 'default', src: SRC, modules: files, source_mb: +(bytes / 1e6).toFixed(1), routes: ROUTES, leaves_per_route: LEAVES, shared: SHARED, module_bytes: BYTES, non_ascii: NON_ASCII, non_ascii_share: NON_ASCII ? NON_ASCII_SHARE : 0 }));
